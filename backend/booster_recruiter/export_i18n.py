"""English wording for service messages in exports.

The service stores its messages in Russian; the window translates them on
display with tr() in src/i18n.js. English exports use the same catalog
(i18n_en.json, generated by scripts/export_i18n_catalog.mjs) and the same
matching order: exact entry, strict template, sentence by sentence, loose
template. Text written by the recruiter or taken from LinkedIn must not be
passed here.
"""

from __future__ import annotations

import json
import re
from functools import cache
from pathlib import Path

_CYRILLIC = re.compile(r"[А-Яа-яЁё]")
# A strict placeholder never crosses a sentence end, so a template such as
# "Профилей сохранено: {count}." cannot swallow the sentences after it.
_STRICT = r"((?:(?![.!?…](?:\s|\Z))[\s\S])*?)"
_LOOSE = r"([\s\S]*?)"
_PLACEHOLDER = re.compile(r"(\{\w+\})")
_SENTENCE = re.compile(r"[^.!?…]+(?:[.!?…]+|\Z)\s*")


@cache
def _catalog():
    data = json.loads(
        (Path(__file__).with_name("i18n_en.json")).read_text(encoding="utf-8")
    )
    compiled = []
    for ru, english in data["templates"].items():
        names, pieces = [], []
        for part in _PLACEHOLDER.split(ru):
            m = re.fullmatch(r"\{(\w+)\}", part)
            if m:
                names.append(m.group(1))
                pieces.append(None)
            else:
                pieces.append(re.escape(part))

        def build(slot, pieces=pieces):
            return re.compile("".join(p if p is not None else slot for p in pieces))

        # Specificity is the fixed text only, as in src/i18n.js.
        fixed = len(re.sub(r"\{\w+\}", "", ru))
        compiled.append(
            {
                "strict": build(_STRICT),
                "loose": build(_LOOSE),
                "names": names,
                "english": english,
                "fixed": fixed,
            }
        )
    # Stable sort keeps catalog order among equals, like Array.prototype.sort.
    compiled.sort(key=lambda e: -e["fixed"])
    return data["strings"], compiled


def _fill(text, values):
    return re.sub(r"\{(\w+)\}", lambda m: str(values.get(m.group(1), m.group(0))), text)


def _by_template(text, depth, mode):
    for entry in _catalog()[1]:
        m = entry[mode].fullmatch(text)
        if not m:
            continue
        values = {}
        for i, name in enumerate(entry["names"]):
            part = m.group(i + 1)
            values[name] = (
                _translate(part, depth + 1) if _CYRILLIC.search(part) else part
            )
        return _fill(entry["english"], values)
    return None


def _exact(text):
    strings = _catalog()[0]
    if text in strings:
        return strings[text]
    trimmed = text.strip()
    if trimmed != text and trimmed in strings:
        return text.replace(trimmed, strings[trimmed], 1)
    return None


def _translate(text, depth):
    if not _CYRILLIC.search(text) or depth > 4:
        return text
    known = _exact(text)
    if known is None:
        known = _by_template(text, depth, "strict")
    if known is not None:
        return known
    sentences = _SENTENCE.findall(text)
    split = None
    if len(sentences) > 1:
        parts = []
        for s in sentences:
            lead = re.match(r"^\s*", s).group(0)
            tail = re.search(r"\s*\Z", s).group(0)
            parts.append(lead + _translate(s.strip(), depth + 1) + tail)
        split = "".join(parts)
        if not _CYRILLIC.search(split):
            return split
    loose = _by_template(text, depth, "loose")
    if loose is not None and not _CYRILLIC.search(loose):
        return loose
    if split is not None:
        return split
    return loose if loose is not None else text


def translate(text):
    """English wording of a stored service message; unknown text is kept."""
    if not isinstance(text, str) or not text:
        return text
    return _translate(text, 0)
